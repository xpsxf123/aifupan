export function normalizeHHmmss(v) {
    const s = String(v || '').trim() /** 统一把输入转成字符串并去掉首尾空格 */
    if (!s) return '' /** 空值直接返回空字符串 */
    if (/^\d{2}:\d{2}$/.test(s)) return `${s}:00` /** 仅有“时:分”时补齐“:秒”，例如 23:50 -> 23:50:00 */
    return s /** 已经包含秒或不是 HH:mm 格式则直接返回原值 */
}

export function buildSchedulesDataWithVideoId(rawSchedules, records) {
    const schedules = Array.isArray(rawSchedules) ? rawSchedules : [] /** 排班列表：非数组时兜底为空数组 */
    const list = Array.isArray(records) ? records : [] /** 录制列表：非数组时兜底为空数组 */
    const result = [] /** 输出：匹配后的排班数据（每条都带上命中的 videoId） */

    for (const schedule of schedules) { /** 遍历每一条排班记录 */
        const workDay = String(schedule?.workDay || '').trim() /** 排班日期（YYYY-MM-DD） */
        const startWork = normalizeHHmmss(schedule?.startWork) /** 排班开始时间（HH:mm 或 HH:mm:ss） */
        const endWork = normalizeHHmmss(schedule?.endWork) /** 排班结束时间（HH:mm 或 HH:mm:ss） */
        if (!workDay || !startWork || !endWork) continue /** 缺少关键字段则跳过该排班 */

        const scheduleStartTime = `${workDay} ${startWork}` /** 拼接成完整开始时间字符串：YYYY-MM-DD HH:mm:ss */
        const scheduleEndTime = `${workDay} ${endWork}` /** 拼接成完整结束时间字符串：YYYY-MM-DD HH:mm:ss */
        const scheduleStartTs = new Date(scheduleStartTime).getTime() /** 排班开始时间戳（ms） */
        const scheduleEndTs = new Date(scheduleEndTime).getTime() /** 排班结束时间戳（ms） */
        if (!Number.isFinite(scheduleStartTs) || !Number.isFinite(scheduleEndTs) || scheduleEndTs <= scheduleStartTs) continue /** 时间非法或区间反向则跳过 */

        const scheduleSecUid = schedule?.secUid || '' /** 排班对应的 secUid（直播间唯一标识之一） */
        if (!scheduleSecUid) continue /** 缺少 secUid 则无法匹配录制数据，直接跳过 */

        for (const record of list) { /** 遍历每一条录制记录，找出该排班包含的录制 */
            const recordSecUid = record?.secUid || record?.anchorInfo?.secUid || '' /** 录制对应的 secUid（兼容从 anchorInfo 取） */
            if (recordSecUid !== scheduleSecUid) continue /** secUid 不一致则不是同一直播间，跳过 */

            const recordStartTs = new Date(record?.startTime).getTime() /** 录制开始时间戳（ms） */
            const recordEndTs = new Date(record?.endTime).getTime() /** 录制结束时间戳（ms） */
            if (!Number.isFinite(recordStartTs) || !Number.isFinite(recordEndTs) || recordEndTs <= recordStartTs) continue /** 录制区间非法则跳过 */

            const isInside = scheduleStartTs <= recordStartTs && recordEndTs <= scheduleEndTs /** 判断：排班区间是否完全包含录制区间 */
            if (!isInside) continue /** 不包含则跳过 */

            const recordVideoId = record?.videoId /** 录制视频的 videoId */
            if (!recordVideoId) continue /** 没有 videoId 则无法回填，跳过 */

            result.push({ /** 回填 videoId 到排班数据里（用于页面后续按 secUid+videoId 做匹配） */
                ...schedule, /** 保留原排班字段 */
                startTime: scheduleStartTime, /** 补充：排班完整开始时间 */
                endTime: scheduleEndTime, /** 补充：排班完整结束时间 */
                videoId: recordVideoId, /** 写入：该排班包含的录制 videoId */
            }) /** 注意：同一排班命中多条录制会生成多条结果记录 */
        }
    }

    return result /** 返回处理后的 schedulesData（用于测试） */
}

